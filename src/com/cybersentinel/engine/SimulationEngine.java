public final class SimulationEngine {
    private static final IncidentService incidentService = new IncidentService();
    private static final IndicatorService indicatorService = new IndicatorService();
    private static final UserDAO userDAO = new UserDAO();

    // Live simulation state
    private static final AtomicBoolean liveSimulationRunning = new AtomicBoolean(false);
    private static Thread liveSimulationThread = null;
    private static final AtomicInteger simulatedGeneratedCount = new AtomicInteger(0);
    private static final List<Consumer<Integer>> countListeners = new ArrayList<>();

    private SimulationEngine() {}

    private static final String[] INCIDENT_TEMPLATES = {
        "Phishing|Urgent Wire Transfer Request from Spoofed CFO Email|Executive assistant received high-urgency email requesting $140,000 international transfer with attached zip file.|Mail Gateway",
        "Ransomware|BlackCat Ransomware Encrypting Shared File Server|Users report files displaying .blackcat extension with RESTORE_FILES.txt instructions demanding 2.5 BTC.|Prod-FileSrv-01",
        "Malware|Cobalt Strike Beacon Detected in Outbound HTTPS Traffic|Network EDR detected periodic HTTPS jitter beaconing from workstation to suspicious external IP.|HR-Laptop-04",
        "Account Compromise|Impossible Travel Login Anomaly for Cloud Administrator|Admin account logged in from New York and 12 minutes later authenticated from Sofia, Bulgaria.|AWS-IAM-Cloud",
        "Data Breach|Mass S3 Bucket Download Detected via Service Account|Automated monitoring detected 45,000 customer PII records downloaded at 03:15 AM via unauthorized key.|S3-Customer-Archive",
        "Network Attack|Distributed SYN Flood Against External Customer Portal|Edge firewall reporting 850,000 SYN packets/sec targeting port 443 with significant connection drops.|Edge-Firewall-01",
        "Unauthorized Access|Privilege Escalation Attempt on Production Database Host|Standard developer service account attempted sudo su execution and kernel exploit script.|Prod-MySQL-Host-02",
        "Suspicious Activity|Unusual Base64 Encoded PowerShell Command Execution|PowerShell executed with -NonInteractive -Hidden flags attempting to download remote payload.|Finance-WS-12"
    };

    private static final String[][] MOCK_IOCS = {
        {"IP Address", "185.220.101.5", "Tor Exit Node involved in reconnaissance"},
        {"Domain", "login-security-verify-portal.com", "Typosquatted credential harvesting portal"},
        {"URL", "http://update-system-patch.online/payload.exe", "Malicious dropper download URL"},
        {"File Hash", "a3c4f728b9911e80931238914ab282c0b65f7281099238491823901283912a3f", "Cobalt Strike beacon DLL"},
        {"Email Address", "finance-update-secure@outlook-cfo-alert.com", "Spoofed executive spearphishing address"},
        {"IP Address", "91.240.118.232", "Known ransomware C2 command server"}
    };

    public static Incident simulateIncident(
            String requestedType,
            Severity requestedSeverity,
            Long assignToAnalystId,
            UserSession session
    ) throws Exception {
        // Pick template
        String template = INCIDENT_TEMPLATES[ThreadLocalRandom.current().nextInt(INCIDENT_TEMPLATES.length)];
        String[] parts = template.split("\\|");
        String type = (requestedType != null && !requestedType.equalsIgnoreCase("RANDOM")) ? requestedType : parts[0];
        String title = parts[1];
        String description = parts[2];
        String affectedSystem = parts[3];

        Severity severity;
        if (requestedSeverity != null) {
            severity = requestedSeverity;
        } else {
            Severity[] sevs = Severity.values();
            severity = sevs[ThreadLocalRandom.current().nextInt(sevs.length)];
        }

        // Find a user ID to attribute as reporter
        long reporterId = session != null ? session.getUserId() : 1L;

        Incident inc = new Incident();
        inc.setTitle("[SIM] " + title);
        inc.setType(type);
        inc.setDescription(description + " [Generated by CyberSentinel SOC Simulator for red-team readiness training]");
        inc.setSeverity(severity);
        inc.setAffectedSystem(affectedSystem);
        inc.setSimulated(true);

        if (assignToAnalystId != null && assignToAnalystId > 0) {
            inc.setAssignedTo(assignToAnalystId);
        }

        // Pass through IncidentService pipeline
        Incident created = incidentService.reportIncident(inc, session);

        // Add a mock IOC to trigger IOC pipeline & threat intel match
        int iocIdx = ThreadLocalRandom.current().nextInt(MOCK_IOCS.length);
        String[] iocData = MOCK_IOCS[iocIdx];
        try {
            indicatorService.addIndicator(created.getId(), iocData[0], iocData[1], iocData[2], session);
        } catch (Exception ignored) {}

        simulatedGeneratedCount.incrementAndGet();
        notifyCountListeners();

        return created;
    }

    public static synchronized void startLiveSimulation(int intervalSeconds, UserSession session) {
        if (liveSimulationRunning.get()) return;

        liveSimulationRunning.set(true);
        liveSimulationThread = new Thread(() -> {
            while (liveSimulationRunning.get()) {
                try {
                    simulateIncident("RANDOM", null, null, session);
                    Thread.sleep(Math.max(5000, intervalSeconds * 1000L));
                } catch (InterruptedException e) {
                    break;
                } catch (Exception e) {
                    System.err.println("[SIMULATOR] Error generating simulated incident: " + e.getMessage());
                }
            }
        }, "CyberSentinel-LiveSimulator");
        liveSimulationThread.setDaemon(true);
        liveSimulationThread.start();
    }

    public static synchronized void stopLiveSimulation() {
        liveSimulationRunning.set(false);
        if (liveSimulationThread != null) {
            liveSimulationThread.interrupt();
            liveSimulationThread = null;
        }
    }

    public static boolean isLiveSimulationRunning() {
        return liveSimulationRunning.get();
    }

    public static int getGeneratedCount() {
        return simulatedGeneratedCount.get();
    }

    public static void addCountListener(Consumer<Integer> listener) {
        if (listener != null) countListeners.add(listener);
    }

    private static void notifyCountListeners() {
        int count = simulatedGeneratedCount.get();
        for (Consumer<Integer> l : countListeners) {
            try { l.accept(count); } catch (Exception ignored) {}
        }
    }
}
